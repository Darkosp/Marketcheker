_CITY_BY_KEY = {normalize_for_match(name): name for name in KNOWN_CITIES}


def find_city_in(text: str | None) -> tuple[str, str] | None:
    """Бара име на град (или скопска општина) во слободен текст.

    Дел од изворите немаат поле за град: Жито го пишува во името
    („2 Трговски - Велес"), Стокомак го има како цело име („КУМАНОВО 2",
    „КИСЕЛА ВОДА"). Ако ништо не се препознае, враќа None - не се погодува.
    """
    key = normalize_for_match(text)
    if not key:
        return None

    # Прво по цртичка: „Трговски - Велес" -> „Велес".
    for dash in ("–", "—", " - "):
        if dash in (text or ""):
            tail = normalize_city((text or "").rsplit(dash, 1)[1])
            if tail:
                return tail

    # Скопските општини и делови.
    for part in SKOPJE_PARTS:
        if part in key:
            return SKOPJE

    # Најдолгото совпаѓање победува: „Нови Село" пред „Село".
    best: str | None = None
    for candidate_key in _CITY_BY_KEY:
        if candidate_key in key and (best is None or len(candidate_key) > len(best)):
            best = candidate_key
    if best is not None:
        return normalize_city(_CITY_BY_KEY[best])
    return None


def slugify(value: str) -> str:
    """Латинична ознака од македонско име: „Кисела Вода" -> „kisela-voda"."""
    text = normalize_for_match(value)
    letters = [_TRANSLITERATION.get(ch, ch) for ch in text]
    slug = re.sub(r"[^a-z0-9]+", "-", "".join(letters))
    return slug.strip("-")


def normalize_city(raw: str | None) -> tuple[str, str] | None:
    """Враќа (slug, име за приказ). Празно име -> None.

    Сите скопски општини и делови даваат ("skopje", "Скопје").
    """
    name = normalize_space(raw)
    if not name:
        return None

    key = normalize_for_match(name)
    if key in SKOPJE_PARTS:
        return SKOPJE

    alias = _ALIASES.get(key)
    if alias is not None:
        return alias

    slug = slugify(name)
    if not slug:
        return None
    # Името за приказ го пишуваме со прва голема буква по збор.
    display = " ".join(word.capitalize() for word in name.split())
    return slug, display
