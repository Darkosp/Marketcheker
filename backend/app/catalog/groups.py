# Под-категорија -> нејзината група.
PARENT_OF: dict[str, str] = {slug: parent for slug, _, parent, _ in SUBCATEGORIES}


def group_of_category(slug: str) -> str:
    """Групата на која припаѓа една категорија (или самата таа, ако е група)."""
    return PARENT_OF.get(slug, slug)


def _kw(slug: str, *words: str, priority: int = 1) -> tuple[Keyword, ...]:
    return tuple(Keyword(slug, word, priority=priority) for word in words)


def _exact(slug: str, *words: str, priority: int = 1) -> tuple[Keyword, ...]:
    """Кратки зборови каде продолжението значи нешто друго.

    „чај" не смее да фати „ЧАЈНИК" (тоа е кујнски прибор), „џин" не смее да
    фати „ВИРЏИН" (тоа е маслиново масло).
    """
    return tuple(
        Keyword(slug, word, priority=priority, whole_word=True) for word in words
    )


def _neg(slug: str, *words: str) -> tuple[Keyword, ...]:
    return tuple(Keyword(slug, word, is_negative=True) for word in words)


