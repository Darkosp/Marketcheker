def group_slugs() -> set[str]:
    return {slug for slug, _, _ in GROUPS}


def category_slugs() -> set[str]:
    """Сите категории, од двете нивоа."""
    return group_slugs() | set(PARENT_OF)


def group_names() -> dict[str, str]:
    return {slug: name for slug, name, _ in GROUPS}


def category_names() -> dict[str, str]:
    names = group_names()
    names.update({slug: name for slug, name, _, _ in SUBCATEGORIES})
    return names
